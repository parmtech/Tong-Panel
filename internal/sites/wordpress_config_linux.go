//go:build linux

package sites

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"io"
	"strings"
	"unicode/utf8"

	"github.com/parmtech/tong-panel/internal/files"
)

const (
	maxWordPressConfigValueBytes = 512
	)

var ErrInvalidWordPressConfig = errors.New("invalid WordPress database configuration")

// WordPressDatabaseConfig contains database settings written to a new,
// private wp-config.php. Callers must obtain values from an approved secret
// store; this helper does not provision a database or retain credentials.
type WordPressDatabaseConfig struct {
	Name        string
	User        string
	Password    string
	Host        string
	TablePrefix string
}

// WriteWordPressDatabaseConfigNew writes a generated wp-config.php beneath an
// already-pinned root. It never replaces an existing file. The file API stages
// privately and publishes with no-replace semantics.
func WriteWordPressDatabaseConfigNew(root *files.Root, relative string, config WordPressDatabaseConfig) error {
	if root == nil || relative == "" {
		return ErrInvalidWordPressConfig
	}
	if config.TablePrefix == "" {
		config.TablePrefix = "wp_"
	}
	if !validWordPressConfigValue(config.Name, false) ||
		!validWordPressConfigValue(config.User, false) ||
		!validWordPressConfigValue(config.Password, false) ||
		!validWordPressConfigValue(config.Host, false) ||
		!validWordPressTablePrefix(config.TablePrefix) {
		return ErrInvalidWordPressConfig
	}

	var salts [8]string
	for index := range salts {
		var random [64]byte
		if _, err := io.ReadFull(rand.Reader, random[:]); err != nil {
			return fmt.Errorf("generate WordPress authentication key: %w", err)
		}
		salts[index] = base64.RawURLEncoding.EncodeToString(random[:])
	}

	var output strings.Builder
	output.WriteString("<?php\n")
	output.WriteString("// Generated by Tong Panel. Keep this file private.\n")
	writePHPDefine(&output, "DB_NAME", config.Name)
	writePHPDefine(&output, "DB_USER", config.User)
	writePHPDefine(&output, "DB_PASSWORD", config.Password)
	writePHPDefine(&output, "DB_HOST", config.Host)
	output.WriteString("define( 'DB_CHARSET', 'utf8mb4' );\n")
	output.WriteString("define( 'DB_COLLATE', '' );\n")
	for index, name := range []string{"AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"} {
		writePHPDefine(&output, name, salts[index])
	}
	output.WriteString("$table_prefix = ")
	output.WriteString(phpSingleQuoted(config.TablePrefix))
	output.WriteString(";\n")
	output.WriteString("define( 'WP_DEBUG', false );\n")
	output.WriteString("if ( ! defined( 'ABSPATH' ) ) { define( 'ABSPATH', __DIR__ . '/' ); }\n")
	output.WriteString("require_once ABSPATH . 'wp-settings.php';\n")

	if err := root.WriteNew(relative, []byte(output.String())); err != nil {
		return fmt.Errorf("write private WordPress configuration: %w", err)
	}
	return nil
}

func writePHPDefine(output *strings.Builder, name, value string) {
	output.WriteString("define( ")
	output.WriteString(phpSingleQuoted(name))
	output.WriteString(", ")
	output.WriteString(phpSingleQuoted(value))
	output.WriteString(" );\n")
}

// phpSingleQuoted encodes PHP's single-quoted string syntax. In this syntax
// dollar signs and interpolation markers are literal; only backslash and
// single quote require escaping.
func phpSingleQuoted(value string) string {
	var output strings.Builder
	output.Grow(len(value) + 2)
	output.WriteByte('\'')
	for index := 0; index < len(value); index++ {
		switch value[index] {
		case '\\', '\'':
			output.WriteByte('\\')
		}
		output.WriteByte(value[index])
	}
	output.WriteByte('\'')
	return output.String()
}

func validWordPressConfigValue(value string, allowEmpty bool) bool {
	if (!allowEmpty && value == "") || len(value) > maxWordPressConfigValueBytes || !utf8.ValidString(value) {
		return false
	}
	for _, character := range value {
		if character < 0x20 || character == 0x7f {
			return false
		}
	}
	return true
}

func validWordPressTablePrefix(prefix string) bool {
	if len(prefix) == 0 || len(prefix) > 16 {
		return false
	}
	for index, character := range prefix {
		if (character < 'a' || character > 'z') &&
			(character < 'A' || character > 'Z') &&
			(character < '0' || character > '9') &&
			character != '_' {
			return false
		}
		if index == 0 && character >= '0' && character <= '9' {
			return false
		}
	}
	return true
}
